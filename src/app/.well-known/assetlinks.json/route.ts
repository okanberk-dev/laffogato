import { getPublicSettings } from "@/lib/admin/store";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * `/.well-known/assetlinks.json` - Android App Links.
 *
 * Android verifies this document at install time and only opens the app for a
 * laffogato.net link when the app's package AND the SHA-256 of the
 * certificate that signed the installed build both appear here.
 *
 * The fingerprint is the reason this is a route and not a file in `public/`.
 * With Play App Signing - which Google now requires for new apps - the
 * certificate users' builds are signed with is **generated by Google after
 * the first upload**, so its fingerprint cannot possibly be known when the
 * site is written. Listing both it and the upload key is normal and
 * necessary: internal-testing builds carry the upload key, Play-distributed
 * builds carry Google's, and a member with the wrong one gets the browser.
 *
 * Missing entries fail closed the same way as the Apple document: 404 rather
 * than an empty array, so Android reads "not configured" instead of "verified
 * as belonging to nobody".
 */
export async function GET() {
  const { mobileApp } = await getPublicSettings();
  const { bundleId, androidSha256 } = mobileApp.store;

  if (!bundleId || androidSha256.length === 0) {
    return new Response("Not Found", {
      status: 404,
      headers: { "Cache-Control": "no-store" },
    });
  }

  const body = [
    {
      relation: [
        "delegate_permission/common.handle_all_urls",
        // Lets Android autofill offer the member's saved laffogato.net
        // password in the app's own sign-in form.
        "delegate_permission/common.get_login_creds",
      ],
      target: {
        namespace: "android_app",
        package_name: bundleId,
        sha256_cert_fingerprints: androidSha256,
      },
    },
  ];

  return new Response(JSON.stringify(body), {
    status: 200,
    headers: {
      "Content-Type": "application/json",
      "Cache-Control": "public, max-age=3600",
    },
  });
}
